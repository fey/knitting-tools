/**
 * Доступ к `localStorage` на весь проект. §10.2 формулирует правило один раз и на все
 * записи — «ни одно чтение и ни одна запись падать не вправе», — и обещает, что
 * реализация тоже одна. Отсюда этот файл: записей уже три (прогресс, свёрнутость
 * вводки, черновик отзыва), и второй копии этих двух функций быть не должно.
 *
 * Чистый TypeScript: Vue здесь нет.
 */

/**
 * Чтение, которому нечего вернуть: записи нет либо хранилище недоступно (приватная
 * вкладка, `file://`, тестовый узел без DOM).
 *
 * **Проверка на недоступность стоит внутри `try`, а не перед ним.** У Chrome
 * с заблокированными данными сайта кидает сам доступ к свойству, то есть и `typeof`;
 * чтения идут при загрузке модуля, и брошенное оттуда уронило бы страницу целиком,
 * а не одну запись.
 */
export function readStored(key: string): string | null {
  try {
    if (typeof localStorage === 'undefined') return null
    return localStorage.getItem(key)
  } catch {
    return null
  }
}

/**
 * Запись, либо стирание записи при `null`. Стирание — это то, как записи выражают
 * «хранить нечего» (§10.2): дефолтное состояние строкой не хранится. Падать не вправе
 * так же, как и чтение.
 */
export function writeStored(key: string, value: string | null): void {
  try {
    if (typeof localStorage === 'undefined') return
    if (value === null) localStorage.removeItem(key)
    else localStorage.setItem(key, value)
  } catch {
    // Хранилище недоступно — запись не переживёт эту сессию, но экран не падает.
  }
}
