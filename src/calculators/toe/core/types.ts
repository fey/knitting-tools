/**
 * Модель расчёта мыска. Словарь — §2 спеки: интервал, повторы, сегмент, ритм,
 * убавочный (прибавочный) и промежуточный ряд.
 *
 * Ядро — чистый TypeScript: импортов из Vue здесь нет и быть не должно.
 */

/** Сегмент ритма: убавочный (прибавочный) ряд, потом `interval` промежуточных, и так `repeats` раз. */
export type Segment = { interval: number; repeats: number }

/** Коды готовых ритмов (§5.4). У каждого направления свой набор — §5.4 спеки toe-up. */
export type PresetName = 'even' | 'accel' | 'thirds' | 'ramp' | 'slow'

/**
 * Направление вязания (§11 спеки toe-up): от манжеты или от мыска. Ядро получает его
 * параметром с дефолтом `'cuff-down'` — страницы разные, код общий.
 */
export type Direction = 'cuff-down' | 'toe-up'

/**
 * Ритм — либо имя пресета, либо набранные руками сегменты (§5.5).
 * У пресета сегментов не хранится: они выводятся от числа убавочных (прибавочных)
 * рядов при каждом расчёте, поэтому пресет пересчитывается живьём сам, а свой ритм
 * остаётся набранным.
 */
export type Rhythm =
  | { kind: 'preset'; name: PresetName }
  | { kind: 'custom'; segments: Segment[] }

/** Ряд мыска. Нумерация с 1, снизу вверх — в порядке вязания. */
export type Row = {
  /** Номер ряда от начала мыска. */
  n: number
  /** Убавочный, прибавочный или промежуточный. */
  type: 'dec' | 'inc' | 'plain'
  /** Порядковый номер убавочного ряда; только у `type === 'dec'`. */
  dec?: number
  /** Порядковый номер прибавочного ряда; только у `type === 'inc'`. */
  inc?: number
  /** Сколько петель в круге после этого ряда. */
  stitches: number
}

/** Входные параметры расчёта (§4). Одни и те же у обоих направлений — §4 спеки toe-up. */
export type ToeParams = {
  /** Начальные петли — сколько петель в круге на момент начала мыска. */
  initial: number
  /** Конечные петли — сколько остаётся к закрытию (§2). */
  final: number
  /** Кромка: сколько петель с краю половины остаётся до места убавки (прибавки). */
  edge: number
  rhythm: Rhythm
}

/** Результат расчёта. */
export type ToeCalculation = ToeParams & {
  /** Направление вязания, которым считали (§11 спеки toe-up). */
  direction: Direction
  /** Сегменты, которыми ритм разложился на этом расчёте. */
  segments: Segment[]
  /** Сколько убавочных (прибавочных) рядов нужно: `|начальные − конечные| / 4`. */
  decRowsNeeded: number
  /** Сколько убавочных (прибавочных) рядов покрыто сегментами. */
  decRowsCovered: number
  rows: Row[]
  /**
   * Число рядов мыска. Самостоятельная величина модели (§13): расчёт по плотности
   * пристыкуется именно к ней — длина = число рядов ÷ плотность по рядам.
   */
  totalRows: number
  /** Недобор (> 0) или перебор (< 0) сегментов относительно нужного числа рядов. */
  lack: number
  /**
   * Сколько петель останется на самом деле. При недоборе больше конечных — мысок
   * встанет на 36 петлях вместо 20 (у toe-up наоборот: меньше конечных). При переборе
   * равно конечным: лишние шаги не выполняются, до них не дойдёт (§9.5).
   */
  finalReal: number
}
