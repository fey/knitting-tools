/**
 * Модель расчёта мыска. Словарь — §2 спеки: интервал, повторы, сегмент, ритм,
 * убавочный и промежуточный ряд.
 *
 * Ядро — чистый TypeScript: импортов из Vue здесь нет и быть не должно.
 */

/** Сегмент ритма: убавочный ряд, потом `interval` промежуточных, и так `repeats` раз. */
export type Segment = { interval: number; repeats: number }

/** Коды готовых ритмов (§5.4). */
export type PresetName = 'even' | 'accel' | 'thirds' | 'ramp'

/**
 * Ритм — либо имя пресета, либо набранные руками сегменты (§5.5).
 * У пресета сегментов не хранится: они выводятся от числа убавочных рядов при каждом
 * расчёте, поэтому пресет пересчитывается живьём сам, а свой ритм остаётся набранным.
 */
export type Rhythm =
  | { kind: 'preset'; name: PresetName }
  | { kind: 'custom'; segments: Segment[] }

/** Ряд мыска. Нумерация с 1, снизу вверх — в порядке вязания. */
export type Row = {
  /** Номер ряда от начала мыска. */
  n: number
  /** Убавочный или промежуточный. */
  type: 'dec' | 'plain'
  /** Порядковый номер убавочного ряда; только у `type === 'dec'`. */
  dec?: number
  /** Сколько петель в круге после этого ряда. */
  stitches: number
}

/** Входные параметры расчёта (§4). */
export type ToeParams = {
  /** Начальные петли — сколько петель в круге на момент начала мыска. */
  initial: number
  /** Конечные петли — сколько остаётся на трикотажный шов. */
  final: number
  /** Кромка: сколько петель с краю половины остаётся до места убавки. */
  edge: number
  rhythm: Rhythm
}

/** Результат расчёта. */
export type ToeCalculation = ToeParams & {
  /** Сегменты, которыми ритм разложился на этом расчёте. */
  segments: Segment[]
  /** Сколько убавочных рядов нужно: `(начальные − конечные) / 4`. */
  decRowsNeeded: number
  /** Сколько убавочных рядов покрыто сегментами. */
  decRowsCovered: number
  rows: Row[]
  /**
   * Число рядов мыска. Самостоятельная величина модели (§13): расчёт по плотности
   * пристыкуется именно к ней — длина = число рядов ÷ плотность по рядам.
   */
  totalRows: number
  /** Недобор (> 0) или перебор (< 0) сегментов относительно нужного числа убавочных. */
  lack: number
  /**
   * Сколько петель останется на самом деле. При недоборе больше конечных — мысок
   * встанет на 36 петлях вместо 20. При переборе равно конечным: лишние шаги
   * не выполняются, до них не дойдёт (§9.5).
   */
  finalReal: number
}
