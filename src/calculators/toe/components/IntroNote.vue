<script setup lang="ts">
/**
 * Вводка — текст в начале страницы: что это за инструмент, куда нажимать, что делать
 * со схемой (§6.1). Стоит первой, до всех ручек, и ради неё порядок экрана переставлен:
 * схема, стоявшая первой, уехала под ручки расчёта (§14).
 *
 * **Не уведомление.** Рамка, подложка и иконка — язык починок и предупреждений (§9.5),
 * и вводка, оформленная как сообщение, была бы прочитана один раз и заклеена взглядом.
 * Поэтому здесь простой текст, мельче основного, без единой рамки.
 *
 * Ширина строки ограничена 42rem (672 px): на широком экране вводка стоит на всю ширину
 * страницы (§6.2), и без ограничения строка растянулась бы на 1300 px, по которым глаз
 * не находит начало следующей. Мера в `rem`, а не в `ch`: `ch` считается от метрик
 * отрисованного шрифта, а он на раннере CI другой — и замер раскладки в тестах поехал бы
 * вместе с ним.
 *
 * Текст ничего не считает и ни на что не подписан: живых чисел тут нет намеренно —
 * они живут у ручек, которые их меняют (§6 «число рядов вплотную к ручке ритма»).
 *
 * Границу конструкции вводка называет прямо («круглый мысок… не считаются»), чтобы
 * настройку, которой нет, не искали в ручках; про кромку здесь не сказано ничего —
 * её объяснение стоит подписью у самой кромки, где по ней и тыкают (`StitchFields.vue`).
 *
 * **Половины круга названы по именам — верх стопы и подошва (тикет #13).** «Круг делится
 * пополам» само по себе не объясняет ни того, почему на схеме стоит одна половина, ни того,
 * почему убавочный ряд снимает четыре петли, а не две. Модель это знает (§3), и вводка —
 * единственное место, где знание доходит до открывшего страницу впервые.
 *
 * **Сворачивается кнопкой и помнит выбор между заходами (тикет #16).** Решение §6.1
 * «видна всегда и не сворачивается» отменено (§14): вводка нужна на первом заходе
 * и мешает на десятом. Страница открывается развёрнутой, кнопка внизу сворачивает,
 * на месте вводки остаётся строка-кнопка — **выход из свёрнутого состояния всегда
 * на виду и не прячется**.
 *
 * Сам выбор хранит `useToeCalculator.ts` второй записью в `localStorage` (§10.2):
 * браузер — его граница, не эта. В hash свёрнутость не попадает никогда (§10.5).
 */
import { useToeCalculator } from '../useToeCalculator'

const { introCollapsed, toggleIntro } = useToeCalculator()

/**
 * Свернуть и развернуть — один переключатель в двух видах, поэтому и вид у кнопок
 * один: мишень 44 px, как у прочих кнопок экрана. Свернувший вводку возвращается
 * к ней тем же пальцем, каким свернул.
 */
const TOGGLE_CLASS = 'flex h-11 items-center self-start rounded border border-slate-300 px-3 text-sm text-slate-700'
</script>

<template>
  <section class="flex max-w-[42rem] flex-col gap-2 text-sm text-slate-600" data-testid="intro">
    <!-- Свёрнутая вводка — одна строка-кнопка на её месте. Прятать её нельзя:
         выход из свёрнутого состояния всегда на виду (§6.1). -->
    <button
      v-if="introCollapsed"
      type="button"
      :class="TOGGLE_CLASS"
      data-testid="intro-expand"
      @click="toggleIntro"
    >
      Показать инструкцию
    </button>

    <template v-else>
      <div class="flex flex-col gap-2" data-testid="intro-body">
        <p>
          Мысок — то, чем носок кончается у пальцев. Считается ленточный мысок: круг делится
          пополам — на верх стопы и подошву, — и убавки идут по краям каждой половины. Поэтому
          убавочный ряд снимает четыре петли: по две с верха стопы и по две с подошвы. Остаток
          закрывают трикотажным швом или стягиванием — это выбор мастера, и калькулятор считает
          петли до него. Круглый мысок, звёздочка и мысок toe-up этим калькулятором не считаются.
        </p>
        <p>
          Начальные петли — сколько их в круге на начало мыска, это число берут из своего носка.
          Конечные — сколько петель останется к закрытию. Дальше выбирается ритм убавок: готовый
          или собранный по шагам. Схема ниже пересчитывается сразу.
        </p>
        <p>
          По схеме и вяжут: ряды читаются снизу вверх, петли справа налево, показана одна
          половина круга из двух. Кнопка внизу отмечает связанные ряды — связанное на схеме
          затеняется.
        </p>
      </div>

      <button
        type="button"
        :class="TOGGLE_CLASS"
        data-testid="intro-collapse"
        @click="toggleIntro"
      >
        Свернуть инструкцию
      </button>
    </template>
  </section>
</template>
