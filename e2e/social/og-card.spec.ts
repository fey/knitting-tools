import { test } from '@playwright/test'

/**
 * Съёмка карточки для соцсетей — `public/og.png` (§11). Это не проверка: спека ничего
 * не утверждает, она пишет файл. Playwright взят затем же, зачем в `screens`: `webServer`
 * сам собирает `dist` и поднимает preview, вьюпорт и браузер уже настроены — самописному
 * скрипту пришлось бы завести всё это заново.
 *
 * Карточка одна на обе страницы. Кадр снимается с калькулятора, а не с витрины: схема —
 * единственное, что на картинке узнаётся с одного взгляда, а список разделов в ленте
 * не отличить от любого другого списка.
 *
 * Вводка сворачивается записью в `localStorage` заранее, как в `e2e/screens/intro-collapsed`:
 * три абзаца текста заняли бы весь кадр, а со свёрнутой вводкой ручки и схема поднимаются
 * под самую шапку.
 */
test('карточка для соцсетей', async ({ page }) => {
  await page.addInitScript(
    ({ key, value }) => localStorage.setItem(key, value),
    { key: 'knitting-tools:intro-collapsed', value: 'collapsed' },
  )
  await page.goto('./toe-band/')

  // Расчёт дефолтный: карточка показывает то же, что видит пришедший по ссылке.
  await page.getByTestId('toe-chart').waitFor()

  // 1280×670 — канонические пропорции карточки 1.91:1 при нетронутой ширине вьюпорта.
  // Резать до 1200 нельзя: схема живёт в правой колонке, и обрезка съела бы её край.
  await page.screenshot({
    path: 'public/og.png',
    clip: { x: 0, y: 0, width: 1280, height: 670 },
  })
})
